/**
 * Генератор идентификаторов сущностей.
 * Префикс кодирует тип: evt_, fnc_, flw_, grp_ — удобно при отладке и в XML-экспорте.
 * Время в base36 + случайный хвост исключают коллизии при любом порядке создания.
 */
export const uid = (prefix = 'id') =>
    `${prefix}_${Date.now().toString(36)}${Math.random().toString(36).slice(2, 8)}`;